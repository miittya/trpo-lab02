"""Простой калькулятор для изучения CI/CD."""


def add(a, b):
    """Вернуть сумму двух чисел."""
    return a + b


def divide(a, b):
    """Вернуть результат деления a на b.

    При делении на ноль вызвать ValueError.
    """
    if b == 0:
        raise ValueError("Деление на ноль запрещено")
    return a / b


def multiply(a, b):
    """Вернуть произведение двух чисел.

    Поддерживаются положительные и отрицательные числа.
    При умножении любого числа на ноль результат равен нулю.

    Пример: multiply(4, 3) возвращает 12.
    """
    return a * b